#!/usr/bin/env python3
"""
normalise.py — turn a BEAUti-generated XML into a benchmark -min.xml

A new benchmark arrives as BEAUti output, which differs from the suite's pattern in a
handful of mechanical ways: the generated banner instead of the benchmark header block, an
old `beast version`, the coalescent reading tree intervals rather than the tree, the log
optimization schedule, output file names carrying the -min suffix, a checkpoint log the
benchmarks do not want, and a chain length that does not give 1000 samples.

This fixes all of those in place, taking the taxon, site and pattern counts from BEAUti's
own comments and the operator weights from the operators themselves. It leaves the data,
the model and the priors exactly as they are.

Then make the other variants with make_variants.py, which needs the -mat one first:

    python3 normalise.py big 3 --source SARS-CoV-2.fasta --beast "java ... -jar beast.jar"
    python3 make_variants.py --datasets big-3 --variants mat --beast "..."
    python3 make_variants.py --datasets big-3 --variants gamma,skygrid --beast "..."

make_variants.py needs the dataset's skygrid cut-off in its CUT_OFFS before that last step.
"""
import argparse
import re
from pathlib import Path

from benchmarks import xml_path
from make_variants import BENCHMARKS, initial_joint

HEADER = """<!-->
Benchmark: benchmark-{dataset}
Source data: {source}
Taxa: {taxa}
Sites: {sites}
Site patterns: {patterns}
Model: JC69, strict clock, coalescent constant population tree prior
Priors: rate ~ ApproximateReferencePrior, popSize ~ Gamma(0.001, 1000)
Operators:
- Scale on rate with weight 3.0
- Scale on popSize with weight 3.0
- SubtreeLeap on tree with weight {leap}
- fixedHeightSPR on tree with weight {spr}
- upDown on rate and popSize with weight 3.0
MCMC length: {states} 
Logging every: {every}
Seed: {seed}
<-->
"""


def counts(xml: str) -> tuple:
    """Taxa, sites and patterns, from the comments BEAUti writes above each block."""
    taxa = int(re.search(r"<!-- ntax=(\d+)\s", xml).group(1))
    sites = int(re.search(r"<!-- ntax=\d+ nchar=(\d+)\s", xml).group(1))
    patterns = int(re.search(r"<!-- npatterns=(\d+)\s", xml).group(1))
    return taxa, sites, patterns


def normalise(xml: str, dataset: str, source: str, states: int, seed: int) -> str:
    taxa, sites, patterns = counts(xml)
    every = states // 1000

    banner = re.search(r"<!-- Generated by BEAUTi.*?-->\n(?=<beast)", xml, re.DOTALL)
    if not banner:
        raise ValueError("no BEAUti banner to replace -- already normalised?")
    leap = re.search(r'<subtreeLeap [^>]*weight="([^"]+)"', xml).group(1)
    spr = re.search(r'<fixedHeightSubtreePruneRegraft weight="([^"]+)"', xml).group(1)
    header = HEADER.format(dataset=dataset, source=source, taxa=taxa, sites=sites,
                           patterns=patterns, leap=f"{float(leap):.1f}", spr=f"{float(spr):.1f}",
                           states=states, every=every, seed=seed)
    xml = xml[:banner.start()] + header + "\n" + xml[banner.end():]

    xml = re.sub(r'<beast version="[\d.]+">', '<beast version="10.5.0">', xml, count=1)

    # The suite's coalescent likelihood refers to the tree directly rather than through intervals
    xml = xml.replace("""		<intervals>
			<treeIntervals>
				<treeModel idref="treeModel"/>
			</treeIntervals>
		</intervals>""", """		<populationTree>
			<treeModel idref="treeModel"/>
		</populationTree>""", 1)

    xml = xml.replace('<operators id="operators" optimizationSchedule="log">',
                      '<operators id="operators" optimizationSchedule="power">', 1)
    xml = re.sub(r'(<mcmc id="mcmc" chainLength=")\d+(" autoOptimize="true")>',
                 rf'\g<1>{states}\g<2> operatorAnalysis="benchmark-{dataset}.ops">', xml, count=1)
    xml = re.sub(r'logEvery="\d+"', f'logEvery="{every}"', xml)
    xml = re.sub(rf'fileName="benchmark-{dataset}-min\.(log|trees)"',
                 lambda m: f'fileName="benchmark-{dataset}.{m.group(1)}"', xml)

    # The benchmarks do not checkpoint
    return re.sub(r"\n\t\t<!-- write state of Markov chain to checkpoint file[^\n]*-->"
                  r"\n\t\t<logCheckpoint[^\n]*\n", "\n", xml)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("type")
    parser.add_argument("number")
    parser.add_argument("--source", default="SOURCE_DATA_UNKNOWN.fasta",
                        help="Name of the alignment the XML was built from, for the header")
    parser.add_argument("--states", type=int, default=1000000,
                        help="Chain length to start from; calibrate it with a sweep (default 1000000)")
    parser.add_argument("--seed", type=int, default=1234)
    parser.add_argument("--beast", default=None,
                        help="BEAST command used to fill in Initial Joint density (omit to leave it out)")
    args = parser.parse_args()

    dataset = f"{args.type}-{args.number}"
    path = xml_path(BENCHMARKS, args.type, args.number, "min")
    xml = normalise(path.read_text(encoding="utf-8"), dataset, args.source, args.states, args.seed)

    if args.beast:
        joint = initial_joint(args.beast, xml, args.seed)
        xml = re.sub(rf"^(Seed: {args.seed})$", lambda m: f"{m.group(1)}\nInitial Joint density: {joint:.4f}",
                     xml, count=1, flags=re.MULTILINE)
        print(f"{path.name}  initial joint {joint:.4f}")
    else:
        print(f"{path.name}  (no Initial Joint density; pass --beast to fill it in)")

    path.write_text(xml, encoding="utf-8")


if __name__ == "__main__":
    main()
